import AsyncStorage from '@react-native-async-storage/async-storage';

import { decrypt, encrypt } from '@/utils/encrypt';

import {
  clearAllEntries,
  deleteOldEntries,
  getAllEntries,
  RETENTION_MS,
  saveEntry,
} from './storage';

jest.mock('@react-native-async-storage/async-storage', () =>
  require('@react-native-async-storage/async-storage/jest/async-storage-mock')
);

jest.mock('expo-secure-store', () => {
  const store = new Map<string, string>();
  return {
    getItemAsync: jest.fn(async (key: string) => store.get(key) ?? null),
    setItemAsync: jest.fn(async (key: string, value: string) => {
      store.set(key, value);
    }),
  };
});

// Real AES-256-GCM via Node's crypto; expo-crypto's native module isn't available in Jest.
jest.mock('expo-crypto', () => require('@/testing/expoCryptoMock'));

const DAY = 24 * 60 * 60 * 1000;
const NOW = new Date('2026-10-08T12:00:00Z').getTime();

async function saveAt(text: string, timestamp: number) {
  jest.setSystemTime(timestamp);
  await saveEntry(text);
}

beforeEach(async () => {
  jest.useFakeTimers({ doNotFake: ['nextTick', 'setImmediate'] });
  await AsyncStorage.clear();
});

afterEach(() => {
  jest.useRealTimers();
});

describe('deleteOldEntries', () => {
  it('deletes entries older than 30 days and keeps newer ones', async () => {
    await saveAt('45 days old', NOW - 45 * DAY);
    await saveAt('31 days old', NOW - 31 * DAY);
    await saveAt('29 days old', NOW - 29 * DAY);
    await saveAt('today', NOW);

    await deleteOldEntries(NOW);

    const texts = (await getAllEntries()).map((e) => e.text);
    expect(texts).toEqual(['29 days old', 'today']);
  });

  it('keeps an entry exactly 30 days old and deletes one a millisecond older', async () => {
    await saveAt('exactly 30 days', NOW - RETENTION_MS);
    await saveAt('30 days and 1ms', NOW - RETENTION_MS - 1);

    await deleteOldEntries(NOW);

    const texts = (await getAllEntries()).map((e) => e.text);
    expect(texts).toEqual(['exactly 30 days']);
  });

  it('does nothing when there are no entries', async () => {
    await expect(deleteOldEntries(NOW)).resolves.toBeUndefined();
    expect(await getAllEntries()).toEqual([]);
  });
});

describe('saveEntry / clearAllEntries', () => {
  it('stores text encrypted, never as plain text', async () => {
    await saveAt('I feel so alone tonight', NOW);

    const raw = (await AsyncStorage.getItem('grace.entries')) ?? '';
    expect(raw).not.toContain('alone');
    expect((await getAllEntries())[0].text).toBe('I feel so alone tonight');
  });

  it('clears every entry', async () => {
    await saveAt('one', NOW);
    await saveAt('two', NOW);

    await clearAllEntries();

    expect(await getAllEntries()).toEqual([]);
  });

  it('skips entries that cannot be decrypted, such as old XOR entries', async () => {
    await saveAt('readable', NOW);
    const stored = JSON.parse((await AsyncStorage.getItem('grace.entries')) ?? '[]');
    stored.push({ id: 'legacy', text: '0a1b2c3d', createdAt: NOW });
    await AsyncStorage.setItem('grace.entries', JSON.stringify(stored));

    const texts = (await getAllEntries()).map((e) => e.text);
    expect(texts).toEqual(['readable']);
  });
});

describe('encrypt / decrypt', () => {
  // 32 bytes, as generated by getOrCreateKey.
  const key = 'a1b2c3d4e5f60718293a4b5c6d7e8f90a1b2c3d4e5f60718293a4b5c6d7e8f90';

  it.each(['plain ascii', 'Pidgin: i don tire 🙏', 'naïve café — “quotes”', ''])(
    'round-trips %p',
    async (text) => {
      expect(await decrypt(await encrypt(text, key), key)).toBe(text);
    }
  );

  it('outputs iv:ciphertext with a fresh 12-byte IV on every call', async () => {
    const a = await encrypt('same text', key);
    const b = await encrypt('same text', key);

    expect(a).toMatch(/^[0-9a-f]{24}:[0-9a-f]+$/);
    expect(a.split(':')[0]).not.toBe(b.split(':')[0]);
    expect(a).not.toBe(b);
  });

  it('rejects tampered ciphertext', async () => {
    const [iv, cipher] = (await encrypt('do not change me', key)).split(':');
    const flipped = (parseInt(cipher[0], 16) ^ 1).toString(16) + cipher.slice(1);

    await expect(decrypt(`${iv}:${flipped}`, key)).rejects.toThrow();
  });

  it('rejects the wrong key', async () => {
    const payload = await encrypt('secret', key);
    const otherKey = 'ff'.repeat(32);

    await expect(decrypt(payload, otherKey)).rejects.toThrow();
  });
});
